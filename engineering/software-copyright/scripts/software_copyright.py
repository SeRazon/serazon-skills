class InputError(Exception):
    """输入文件缺失、格式错误或参数非法。"""


@dataclass
class Issue:
    severity: str
    code: str
    message: str
    file: Optional[str] = None
    line: Optional[int] = None

    def as_dict(self) -> dict:
        data = {"severity": self.severity, "code": self.code, "message": self.message}
        if self.file is not None:
            data["file"] = self.file
        if self.line is not None:
            data["line"] = self.line
        return data


class Audit:
    def __init__(self, strict: bool = False) -> None:
        self.strict = strict
        self.errors: List[Issue] = []
        self.warnings: List[Issue] = []
        self.stats: Dict[str, object] = {}

    def error(
        self, code: str, message: str, file: Optional[str] = None, line: Optional[int] = None
    ) -> None:
        self.errors.append(Issue("error", code, message, file, line))

    def warning(
        self, code: str, message: str, file: Optional[str] = None, line: Optional[int] = None
    ) -> None:
        self.warnings.append(Issue("warning", code, message, file, line))

    @property
    def ok(self) -> bool:
        return not self.errors and not (self.strict and self.warnings)


def display_path(path: Path) -> str:
    try:
        return str(path.resolve().relative_to(Path.cwd().resolve()))
    except ValueError:
        return str(path)


def rel_posix(path: Path, root: Path) -> str:
    return path.relative_to(root).as_posix()


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def md_escape(value: str) -> str:
    return value.replace("|", "\\|")


def is_secret_file(name: str) -> bool:
    lower = name.lower()
    if lower == ".env" or lower.startswith(".env."):
        return True
    if lower in {
        "credentials.json", "credentials.yaml", "credentials.yml", "credentials.toml",
        "secrets.json", "secrets.yaml", "secrets.yml", "secrets.toml",
    }:
        return True
    if lower.startswith(("id_rsa", "id_ed25519")):
        return True
    return Path(lower).suffix in SECRET_SUFFIXES


def is_test_path(rel: str) -> bool:
    parts = rel.lower().split("/")
    if any(part in TEST_DIRS for part in parts[:-1]):
        return True
    return bool(TEST_FILE_RE.match(parts[-1]))


def decode_text(data: bytes) -> Optional[Tuple[str, str]]:
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        try:
            return data.decode("utf-16"), "utf-16"
        except UnicodeDecodeError:
            return None
    for encoding in ("utf-8-sig", "gb18030"):
        try:
            return data.decode(encoding), encoding
        except UnicodeDecodeError:
            continue
    return None


def is_binary(data: bytes) -> bool:
    if data.startswith((b"\xff\xfe", b"\xfe\xff")):
        return False
    return b"\x00" in data[:8192]


def is_image_file(path: Path) -> bool:
    try:
        head = path.read_bytes()[:12]
    except OSError:
        return False
    if head.startswith(b"RIFF") and head[8:12] == b"WEBP":
        return True
    return any(head.startswith(magic) for magic in IMAGE_MAGIC)


def is_generated(text: str) -> bool:
    head = "\n".join(text.splitlines()[:20]).lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def is_minified(lines: Sequence[str]) -> bool:
    if not lines:
        return False
    lengths = [len(line) for line in lines]
    return max(lengths) > 2000 or (sum(lengths) / len(lengths)) > 300


def build_manifest(args: argparse.Namespace) -> dict:
    root = args.project.resolve()
    if not root.is_dir():
        raise InputError(f"项目目录不存在：{args.project}")

    include_ext = set(DEFAULT_EXTS)
    if args.include_ext:
        include_ext.update(args.include_ext)
    normalized = set()
    for ext in include_ext:
        normalized.add(ext.lower() if ext.startswith(".") else "." + ext.lower())

    files: List[dict] = []
    warnings: List[str] = []
    excluded = Counter()
    excluded_dirs: List[str] = []

    for dirpath, dirnames, filenames in os.walk(root):
        current = Path(dirpath)
        kept_dirs = []
        for dirname in sorted(dirnames):
            child = current / dirname
            rel = rel_posix(child, root)
            lower = dirname.lower()
            if child.is_symlink():
                excluded["symlink"] += 1
                warnings.append(f"跳过符号链接目录：{rel}")
                continue
            if dirname.startswith(".") or lower in EXCLUDE_DIRS:
                excluded["directory"] += 1
                excluded_dirs.append(rel)
                continue
            if not args.include_tests and lower in TEST_DIRS:
                excluded["test"] += 1
                excluded_dirs.append(rel)
                continue
            kept_dirs.append(dirname)
        dirnames[:] = kept_dirs

        for filename in sorted(filenames):
            path = current / filename
            rel = rel_posix(path, root)
            lower = filename.lower()
            suffix = path.suffix.lower()

            if path.is_symlink():
                excluded["symlink"] += 1
                warnings.append(f"跳过符号链接文件：{rel}")
                continue
            if is_secret_file(filename):
                excluded["secret"] += 1
                warnings.append(f"跳过疑似密钥文件：{rel}")
                continue
            if filename.startswith("."):
                excluded["hidden"] += 1
                continue
            if lower in LOCK_NAMES or lower.endswith((".lock", ".sum", ".map", ".min.js", ".min.css")):
                excluded["lock"] += 1
                continue
            if suffix not in normalized:
                continue
            if not args.include_tests and is_test_path(rel):
                excluded["test"] += 1
                continue

            try:
                data = path.read_bytes()
            except OSError as exc:
                excluded["unreadable"] += 1
                warnings.append(f"无法读取 {rel}：{exc}")
                continue
            if len(data) > args.max_file_bytes:
                excluded["too_large"] += 1
                warnings.append(f"跳过超过 {args.max_file_bytes} 字节的文件：{rel}")
                continue
            if is_binary(data):
                excluded["binary"] += 1
                continue
            decoded = decode_text(data)
            if decoded is None:
                excluded["encoding"] += 1
                warnings.append(f"无法按 UTF-8/GB18030 解码，已跳过：{rel}")
                continue
            text, encoding = decoded
            if not text.strip():
                excluded["empty"] += 1
                continue
            if is_generated(text):
                excluded["generated"] += 1
                warnings.append(f"疑似生成文件，已跳过：{rel}")
                continue
            lines = text.splitlines()
            if is_minified(lines):
                excluded["minified"] += 1
                warnings.append(f"疑似压缩/生成文件，已跳过：{rel}")
                continue

            nonblank = sum(1 for line in lines if line.strip())
            files.append(
                {
                    "path": rel,
                    "language": LANGUAGES.get(suffix, suffix.lstrip(".").upper() or "Text"),
                    "bytes": len(data),
                    "lines": len(lines),
                    "nonblank_lines": nonblank,
                    "encoding": encoding,
                    "sha256": sha256_bytes(data),
                }
            )

    if not files:
        raise InputError("没有找到可纳入的源码文件；请检查 --project 或 --include-ext")

    files.sort(key=lambda item: (0 if Path(item["path"]).name.lower() in ENTRY_FILES else 1, item["path"]))
    totals = {
        "files": len(files),
        "raw_lines": sum(item["lines"] for item in files),
        "nonblank_lines": sum(item["nonblank_lines"] for item in files),
        "bytes": sum(item["bytes"] for item in files),
    }
    language_totals: Dict[str, dict] = {}
    for item in files:
        language = item["language"]
        entry = language_totals.setdefault(language, {"files": 0, "lines": 0})
        entry["files"] += 1
        entry["lines"] += item["lines"]

    return {
        "schema": SCHEMA_VERSION,
        "tool": "software-copyright",
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "project_root": str(root),
        "settings": {
            "include_tests": bool(args.include_tests),
            "include_ext": sorted(normalized),
            "max_file_bytes": args.max_file_bytes,
        },
        "files": files,
        "totals": totals,
        "languages": language_totals,
        "excluded": dict(excluded),
        "excluded_dirs": excluded_dirs[:100],
        "warnings": warnings[:200],
        "warnings_truncated": len(warnings) > 200,
    }


def write_stats(manifest: dict, out_path: Path) -> None:
    totals = manifest["totals"]
    lines = [
        "# 源程序统计",
        "",
        f"- 项目：`{manifest['project_root']}`",
        f"- 生成时间：{manifest['generated_at']}",
        f"- 文件数：{totals['files']}",
        f"- 总行数：{totals['raw_lines']}",
        f"- 非空行：{totals['nonblank_lines']}",
        f"- 总字节：{totals['bytes']}",
        "",
        "| 文件 | 语言 | 行数 | 非空行 | 字节 |",
        "|---|---|---:|---:|---:|",
    ]
    for item in manifest["files"]:
        lines.append(
            f"| `{md_escape(item['path'])}` | {item['language']} | "
            f"{item['lines']} | {item['nonblank_lines']} | {item['bytes']} |"
        )
    if manifest.get("excluded_dirs"):
        lines.extend(["", "## 已排除目录", ""])
        for directory in manifest["excluded_dirs"]:
            lines.append(f"- `{directory}`")
    if manifest.get("warnings"):
        lines.extend(["", "## 警告", ""])
        for warning in manifest["warnings"]:
            lines.append(f"- {warning}")
        if manifest.get("warnings_truncated"):
            lines.append("- 警告过多，仅显示前 200 条")
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_manifest(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except OSError as exc:
        raise InputError(f"无法读取 {path}：{exc}")
    except json.JSONDecodeError as exc:
        raise InputError(f"{path} 不是合法 JSON：第 {exc.lineno} 行：{exc.msg}")
    if not isinstance(data, dict) or data.get("schema") != SCHEMA_VERSION:
        raise InputError(f"{path} 不是本工具生成的 source_manifest.json")
    if not isinstance(data.get("files"), list) or not data["files"]:
        raise InputError(f"{path} 中没有可用的 files")
    return data


def char_width(char: str) -> int:
    return 2 if unicodedata.east_asian_width(char) in ("W", "F") else 1


def wrap_line(line: str, max_cols: int) -> List[str]:
    if not line:
        return [""]
    chunks: List[str] = []
    buffer = ""
    width = 0
    for char in line:
        char_w = char_width(char)
        if buffer and width + char_w > max_cols:
            chunks.append(buffer)
            buffer = char
            width = char_w
        else:
            buffer += char
            width += char_w
    chunks.append(buffer)
    return chunks


def comment_prefix(path: str) -> str:
    suffix = Path(path).suffix.lower()
    if suffix in {".py", ".rb", ".sh", ".bash", ".ps1", ".r", ".jl", ".yaml", ".yml"}:
        return "#"
    if suffix in {".html", ".htm", ".xml", ".vue", ".svelte", ".astro"}:
        return "<!--"
    if suffix == ".sql":
        return "--"
    if suffix in {".css", ".scss", ".less"}:
        return "/*"
    return "//"


def separator_line(path: str) -> str:
    prefix = comment_prefix(path)
    if prefix == "<!--":
        return f"<!-- {path} -->"
    if prefix == "/*":
        return f"/* {path} */"
    return f"{prefix} {path}"


def read_project_file(root: Path, rel: str, expected_hash: str, encoding: str) -> str:
    path = (root / rel).resolve()
    try:
        path.relative_to(root.resolve())
    except ValueError:
        raise InputError(f"清单路径越出项目目录：{rel}")
    try:
        data = path.read_bytes()
    except OSError as exc:
        raise InputError(f"无法读取 {rel}：{exc}")
    if sha256_bytes(data) != expected_hash:
        raise InputError(f"{rel} 自 scan 后已变化，请重新运行 scan")
    try:
        return data.decode(encoding)
    except (LookupError, UnicodeDecodeError):
        decoded = decode_text(data)
        if decoded is None:
            raise InputError(f"无法解码 {rel}")
        return decoded[0]


def build_display_lines(
    manifest: dict, project_root: Path, max_cols: int, keep_blank: bool
) -> Tuple[List[Tuple[str, str]], List[str]]:
    display: List[Tuple[str, str]] = []
    warnings: List[str] = []
    for item in manifest["files"]:
        rel = item["path"]
        text = read_project_file(
            project_root, rel, item.get("sha256", ""), item.get("encoding", "utf-8")
        )
        file_lines: List[str] = []
        for raw in text.splitlines():
            line = raw.expandtabs(4).rstrip()
            if not keep_blank and not line.strip():
                continue
            file_lines.extend(wrap_line(line, max_cols))
        if not file_lines:
            continue
        for chunk in wrap_line(separator_line(rel), max_cols):
            display.append((rel, chunk))
        for chunk in file_lines:
            display.append((rel, chunk))
    if not display:
        raise InputError("清单中的源码去掉空白行后为空")
    if len(display) < LINES_PER_PAGE:
        warnings.append(
            f"源程序只有 {len(display)} 行，不足一页 {LINES_PER_PAGE} 行；"
            "官方对每页行数的要求可能无法满足，请确认项目是否过小。"
        )
    return display, warnings


def select_pages(
    display: List[Tuple[str, str]], max_pages: int
) -> Tuple[List[Tuple[str, str]], str, List[str]]:
    total_pages = math.ceil(len(display) / LINES_PER_PAGE)
    warnings: List[str] = []
    if total_pages <= max_pages:
        selected = display
        mode = "all"
    else:
        if max_pages % 2 != 0:
            raise InputError("--max-pages 必须是偶数")
        half = max_pages // 2
        selected = display[: half * LINES_PER_PAGE] + display[-half * LINES_PER_PAGE :]
        mode = "first_last"
        warnings.append(
            f"源程序共 {total_pages} 页，超过 {max_pages} 页；"
            f"已按官方一般交存取前 {half} 页和后 {half} 页。"
        )
    if len(selected) % LINES_PER_PAGE:
        warnings.append("最后一页不足 50 行；官方允许结束页少于 50 行，请保留。")
    return selected, mode, warnings


def page_files(selected: List[Tuple[str, str]]) -> List[List[str]]:
    pages: List[List[str]] = []
    for start in range(0, len(selected), LINES_PER_PAGE):
        chunk = selected[start : start + LINES_PER_PAGE]
        files: List[str] = []
        for rel, _ in chunk:
            if rel not in files:
                files.append(rel)
        pages.append(files)
    return pages


def render_html(name: str, version: str, selected: List[Tuple[str, str]]) -> str:
    title = f"{name} {version}".strip()
    chunks = [selected[i : i + LINES_PER_PAGE] for i in range(0, len(selected), LINES_PER_PAGE)]
    parts = [
        "<!doctype html>",
        '<html lang="zh-CN">',
        "<head>",
        '<meta charset="utf-8">',
        f"<title>{html.escape(title)} - 源程序文档</title>",
        "<style>",
        "@page { size: A4; margin: 0; }",
        "html, body { margin: 0; padding: 0; background: #fff; color: #000; }",
        ".page { width: 210mm; height: 297mm; padding: 14mm 15mm 12mm 15mm; "
        "box-sizing: border-box; position: relative; page-break-after: always; overflow: hidden; }",
        ".page:last-of-type { page-break-after: auto; }",
        "header { display: flex; justify-content: space-between; align-items: flex-end; "
        'font-family: "SimSun", "Songti SC", serif; font-size: 9pt; line-height: 1.2; '
        "border-bottom: 0.4pt solid #000; padding-bottom: 2mm; margin-bottom: 3mm; }",
        ".doc-title { font-weight: 600; }",
        ".code { margin: 0; font-family: \"Courier New\", Consolas, \"Liberation Mono\", monospace; "
        "font-size: 9pt; line-height: 1.35; white-space: pre; }",
        ".line { display: block; min-height: 1.35em; }",
        "@media print { .page { break-after: page; } .page:last-of-type { break-after: auto; } }",
        "</style>",
        "</head>",
        "<body>",
    ]
    for index, chunk in enumerate(chunks, start=1):
        parts.append(f'<section class="page" data-page="{index}">')
        parts.append(
            f'<header><span class="doc-title">{html.escape(title)}</span>'
            f'<span class="page-no">第 {index} 页</span></header>'
        )
        parts.append('<pre class="code">')
        lines_html = "".join(
            f'<span class="line">{html.escape(line, quote=False)}</span>'
            for _, line in chunk
        )
        parts.append(lines_html)
        parts.append("</pre>")
        parts.append("</section>")
    parts.extend(["</body>", "</html>", ""])
    return "\n".join(parts)


def cmd_scan(args: argparse.Namespace) -> int:
    manifest = build_manifest(args)
    out_dir = args.out.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = out_dir / "source_manifest.json"
    stats_path = out_dir / "source_stats.md"
    try:
        manifest_path.write_text(
            json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        write_stats(manifest, stats_path)
    except OSError as exc:
        raise InputError(f"无法写入输出目录 {out_dir}：{exc}")

    totals = manifest["totals"]
    print(
        f"扫描完成：{totals['files']} 个文件，{totals['raw_lines']} 行"
        f"（非空 {totals['nonblank_lines']} 行）"
    )
    if manifest["excluded"]:
        summary = "，".join(f"{key}={value}" for key, value in sorted(manifest["excluded"].items()))
        print(f"已排除：{summary}")
    if manifest["warnings"]:
        print(f"警告：{len(manifest['warnings'])} 条（详见 source_stats.md）")
    print(f"清单：{display_path(manifest_path)}")
    print(f"统计：{display_path(stats_path)}")
    return 0


def cmd_render(args: argparse.Namespace) -> int:
    manifest = load_manifest(args.manifest)
    root = args.project.resolve() if args.project else Path(manifest["project_root"])
    if not root.is_dir():
        raise InputError(f"项目目录不存在：{root}")
    if args.max_pages < 2 or args.max_pages > 120:
        raise InputError("--max-pages 应在 2..120 之间")
    if args.max_cols < 40 or args.max_cols > 160:
        raise InputError("--max-cols 应在 40..160 之间")
    if not args.name.strip() or not args.version.strip():
        raise InputError("--name 和 --version 不能为空")
    if any(char in args.name + args.version for char in "\r\n"):
        raise InputError("--name / --version 不能包含换行")

    display, warnings = build_display_lines(
        manifest, root, max_cols=args.max_cols, keep_blank=args.keep_blank_lines
    )
    selected, mode, selection_warnings = select_pages(display, args.max_pages)
    warnings.extend(selection_warnings)
    pages = math.ceil(len(selected) / LINES_PER_PAGE)
    files_by_page = page_files(selected)
    html_text = render_html(args.name, args.version, selected)

    out_path = args.out.resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        out_path.write_text(html_text, encoding="utf-8", newline="\n")
    except OSError as exc:
        raise InputError(f"无法写入 {out_path}：{exc}")

    sidecar = out_path.with_suffix(".manifest.json")
    sidecar_data = {
        "schema": SCHEMA_VERSION,
        "name": args.name,
        "version": args.version,
        "source_html": out_path.name,
        "pages": pages,
        "lines_per_page": LINES_PER_PAGE,
        "max_pages": args.max_pages,
        "max_cols": args.max_cols,
        "selected": mode,
        "total_display_lines": len(display),
        "selected_display_lines": len(selected),
        "source_raw_lines": manifest["totals"]["raw_lines"],
        "source_nonblank_lines": manifest["totals"]["nonblank_lines"],
        "source_files": [item["path"] for item in manifest["files"]],
        "project_root": str(root),
        "page_files": files_by_page,
        "warnings": warnings,
    }
    try:
        sidecar.write_text(
            json.dumps(sidecar_data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
    except OSError as exc:
        raise InputError(f"无法写入 {sidecar}：{exc}")
    print(
        f"生成源程序文档：{pages} 页，{len(selected)} 个显示行，"
        f"{'前30页+后30页' if mode == 'first_last' else '全部源码'}"
    )
    for warning in warnings:
        print(f"警告：{warning}")
    print(f"HTML：{display_path(out_path)}")
    print(f"清单：{display_path(sidecar)}")
    print("打印：A4、边距 None、缩放 100%，保存为 PDF。")
    return 0


@dataclass
class ParsedPage:
    number: int
    header: str
    page_no: Optional[int]
    lines: List[str]


def parse_source_html(path: Path) -> List[ParsedPage]:
    try:
        text = path.read_text(encoding="utf-8-sig")
    except OSError as exc:
        raise InputError(f"无法读取 {path}：{exc}")
    sections = re.findall(
        r'<section\s+class="page"\s+data-page="(\d+)"\s*>(.*?)</section>', text, re.S
    )
    if not sections:
        raise InputError(f"{path} 中没有识别到 .page 页面，请使用本工具生成的 HTML")
    pages: List[ParsedPage] = []
    for index, (number, body) in enumerate(sections, start=1):
        header_match = re.search(r"<header>(.*?)</header>", body, re.S)
        header = ""
        if header_match:
            header = re.sub(r"<[^>]+>", " ", header_match.group(1))
            header = re.sub(r"\s+", " ", html.unescape(header)).strip()
        page_no_match = re.search(r'<span class="page-no">\s*第\s*(\d+)\s*页\s*</span>', body)
        page_no = int(page_no_match.group(1)) if page_no_match else None
        lines = [
            html.unescape(value)
            for value in re.findall(r'<span class="line">(.*?)</span>', body, re.S)
        ]
        pages.append(ParsedPage(int(number), header, page_no, lines))
    return pages


def load_json_object(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig"))
    except OSError as exc:
        raise InputError(f"无法读取 {path}：{exc}")
    except json.JSONDecodeError as exc:
        raise InputError(f"{path} 不是合法 JSON：第 {exc.lineno} 行：{exc.msg}")
    if not isinstance(data, dict):
        raise InputError(f"{path} 顶层必须是对象")
    return data


def load_info(path: Path) -> dict:
    return load_json_object(path)


def parse_iso_date(value: str) -> Optional[date]:
    try:
        return date.fromisoformat(value)
    except (TypeError, ValueError):
        return None


def check_info(info: dict, pages: List[ParsedPage], sidecar: Optional[dict], audit: Audit) -> None:
    required = [
        "software_name", "version", "completion_date", "copyright_owner",
        "development_method", "rights_scope", "hardware_env", "software_env",
        "languages", "source_lines", "purpose", "domain", "main_functions",
        "technical_features", "publication_status",
    ]
    for field in required:
        value = info.get(field)
        if value is None or (isinstance(value, str) and not value.strip()):
            audit.error("INFO_MISSING", f"申请表信息缺少字段：{field}", file="application-info.json")

    name = str(info.get("software_name") or "").strip()
    version = str(info.get("version") or "").strip()
    if name and pages and name not in pages[0].header:
        audit.error("INFO_NAME_MISMATCH", f"申请表中的软件名称「{name}」未出现在源程序页眉")
    if version and pages and version not in pages[0].header:
        audit.error("INFO_VERSION_MISMATCH", f"申请表中的版本号「{version}」未出现在源程序页眉")

    if version and not re.match(r"^[Vv]?\d+(\.\d+){0,3}$", version):
        audit.warning("INFO_VERSION_FORMAT", f"版本号「{version}」建议使用 V1.0 或 1.0 形式")

    today = date.today()
    completion = parse_iso_date(str(info.get("completion_date") or ""))
    if completion is None:
        audit.error("INFO_DATE", "completion_date 需为 YYYY-MM-DD")
    elif completion > today:
        audit.error("INFO_DATE", "开发完成日期不能晚于今天")
    elif completion.year < 1980:
        audit.warning("INFO_DATE", "开发完成日期早于 1980 年，请确认")

    status = str(info.get("publication_status") or "").strip()
    if status not in {"已发表", "未发表"}:
        audit.error("INFO_PUBLICATION", "publication_status 需为 已发表 / 未发表")
    elif status == "已发表":
        pub_date = parse_iso_date(str(info.get("first_publication_date") or ""))
        if pub_date is None:
            audit.error("INFO_PUBLICATION", "已发表时需填写 first_publication_date（YYYY-MM-DD）")
        else:
            if pub_date > today:
                audit.error("INFO_PUBLICATION", "首次发表日期不能晚于今天")
            if completion and pub_date < completion:
                audit.error("INFO_PUBLICATION", "首次发表日期不能早于开发完成日期")
        if not str(info.get("first_publication_place") or "").strip():
            audit.error("INFO_PUBLICATION", "已发表时需填写 first_publication_place")

    method = str(info.get("development_method") or "").strip()
    if method and method not in {"独立开发", "合作开发", "委托开发", "下达任务开发"}:
        audit.warning("INFO_METHOD", f"开发方式「{method}」建议使用官方枚举值")

    source_lines = info.get("source_lines")
    if not isinstance(source_lines, int) or source_lines <= 0:
        audit.error("INFO_SOURCE_LINES", "source_lines 需为正整数")
    elif sidecar:
        raw = sidecar.get("source_raw_lines")
        if isinstance(raw, int) and raw > 0:
            tolerance = max(10, int(raw * 0.1))
            if abs(source_lines - raw) > tolerance:
                audit.warning(
                    "INFO_SOURCE_LINES",
                    f"source_lines={source_lines} 与扫描总行数 {raw} 相差超过 10%，请确认口径",
                )

    functions = str(info.get("main_functions") or "").strip()
    if functions and len(functions) < 200:
        audit.warning(
            "INFO_FUNCTIONS_SHORT",
            "main_functions 少于 200 字；2026 年新规常见要求为 500–1300 字，请按最新表单核对",
        )
    if functions and len(functions) > 1300:
        audit.warning("INFO_FUNCTIONS_LONG", "main_functions 超过 1300 字，请按最新表单核对上限")

    if not str(info.get("ai_usage") or "").strip():
        audit.warning(
            "INFO_AI_USAGE",
            "未填写 ai_usage；如使用过 AI 辅助，请按最新申请表要求如实声明",
        )


def manual_text(path: Path) -> Tuple[str, str]:
    try:
        raw = path.read_text(encoding="utf-8-sig")
    except OSError as exc:
        raise InputError(f"无法读取 {path}：{exc}")
    if path.suffix.lower() in {".html", ".htm"}:
        text = re.sub(r"<(script|style)\b.*?</\1>", "", raw, flags=re.S | re.I)
        text = re.sub(r"<br\s*/?>", "\n", text, flags=re.I)
        text = re.sub(r"</(p|div|li|tr|h[1-6]|section|article)>", "\n", text, flags=re.I)
        text = re.sub(r"<[^>]+>", "", text)
        return raw, html.unescape(text)
    return raw, raw


def manual_headings(path: Path, raw: str, text: str) -> List[str]:
    headings = re.findall(r"^#{1,6}\s+(.+)$", text, re.M)
    if path.suffix.lower() in {".html", ".htm"}:
        headings += [
            html.unescape(re.sub(r"<[^>]+>", "", value))
            for value in re.findall(r"<h[1-6][^>]*>(.*?)</h[1-6]>", raw, re.S | re.I)
        ]
    return headings


def check_manual(
    path: Path,
    info: Optional[dict],
    pages: List[ParsedPage],
    audit: Audit,
) -> None:
    raw, text = manual_text(path)
    non_empty = [line for line in text.splitlines() if line.strip()]
    if not non_empty:
        audit.error("MANUAL_EMPTY", "用户手册没有有效内容", file=str(path))
        return
    estimated_pages = math.ceil(len(non_empty) / 30)
    audit.stats["manual_lines"] = len(non_empty)
    audit.stats["manual_estimated_pages"] = estimated_pages
    if estimated_pages > 60:
        audit.warning(
            "MANUAL_TOO_LONG",
            f"按 30 行/页估算约 {estimated_pages} 页，超过 60 页；请按官方要求截取前后各 30 页",
            file=str(path),
        )

    headings = manual_headings(path, raw, text)
    heading_text = " ".join(headings)
    sections = {
        "软件概述": ("概述", "简介", "软件介绍"),
        "运行环境": ("运行环境", "环境要求", "配置要求"),
        "安装启动": ("安装", "部署", "启动", "登录"),
        "操作说明": ("操作", "使用说明", "功能说明", "功能"),
        "常见问题": ("常见问题", "FAQ", "故障", "异常"),
    }
    for label, keywords in sections.items():
        if not any(keyword.lower() in heading_text.lower() for keyword in keywords):
            audit.warning(
                "MANUAL_SECTION",
                f"用户手册未识别到「{label}」相关章节，请确认结构完整",
                file=str(path),
            )

    image_count = len(re.findall(r"!\[[^\]]*\]\([^)]+\)", raw))
    image_count += len(re.findall(r"<img\b", raw, re.I))
    audit.stats["manual_images"] = image_count
    if image_count == 0:
        audit.warning(
            "MANUAL_NO_IMAGE",
            "用户手册没有截图；软著文档通常需要真实界面截图，请补充",
            file=str(path),
        )

    placeholders = PLACEHOLDER_ERROR_RE.findall(text)
    if placeholders:
        audit.error(
            "MANUAL_PLACEHOLDER",
            f"用户手册仍含占位内容（{', '.join(sorted(set(placeholders)))}），提交前必须替换",
            file=str(path),
        )
    if TODO_RE.search(text):
        audit.warning("MANUAL_TODO", "用户手册含 TODO/FIXME，请确认不是未完成内容", file=str(path))

    probe = "\n".join(non_empty[:40])
    name = str((info or {}).get("software_name") or "").strip()
    version = str((info or {}).get("version") or "").strip()
    if not name and pages:
        header = pages[0].header
        if not header:
            audit.warning("MANUAL_TITLE", "用户手册未识别到软件名称，建议在封面/页眉写明", file=str(path))
    elif name and name not in probe:
        audit.warning(
            "MANUAL_TITLE",
            f"用户手册前 40 行未出现软件名称「{name}」，建议在封面/页眉补充",
            file=str(path),
        )
    if version and version not in probe:
        audit.warning(
            "MANUAL_TITLE",
            f"用户手册前 40 行未出现版本号「{version}」，建议在封面/页眉补充",
            file=str(path),
        )


def format_pages(numbers: Sequence[str], limit: int = 10) -> str:
    if len(numbers) <= limit:
        return "、".join(numbers)
    return "、".join(numbers[:limit]) + f" 等 {len(numbers)} 页"


def check_source_pages(
    pages: List[ParsedPage],
    name: str,
    version: str,
    sidecar: Optional[dict],
    audit: Audit,
) -> None:
    if not pages:
        audit.error("SOURCE_EMPTY", "源程序文档没有页面")
        return
    if len(pages) > 60:
        audit.error("SOURCE_TOO_MANY_PAGES", f"源程序文档有 {len(pages)} 页，超过 60 页")
    audit.stats["source_pages"] = len(pages)
    total_lines = sum(len(page.lines) for page in pages)
    audit.stats["source_visible_lines"] = total_lines

    missing_header: List[str] = []
    missing_name: List[str] = []
    missing_version: List[str] = []
    for index, page in enumerate(pages, start=1):
        if page.number != index:
            audit.error(
                "SOURCE_PAGE_NUMBER",
                f"页面 data-page={page.number} 与顺序 {index} 不一致",
            )
        if page.page_no != index:
            audit.error(
                "SOURCE_PAGE_NO",
                f"第 {index} 页页眉页码为 {page.page_no!r}，应为 {index}",
            )
        if not page.header:
            missing_header.append(str(index))
        else:
            if name and name not in page.header:
                missing_name.append(str(index))
            if version and version not in page.header:
                missing_version.append(str(index))
        if index < len(pages):
            if len(page.lines) < LINES_PER_PAGE:
                audit.error(
                    "SOURCE_LINES",
                    f"第 {index} 页只有 {len(page.lines)} 行，应为 {LINES_PER_PAGE} 行",
                )
        elif not page.lines:
            audit.error("SOURCE_LINES", f"第 {index} 页为空")

    if missing_header:
        audit.error("SOURCE_HEADER", f"以下页面缺少页眉：{format_pages(missing_header)}")
    if missing_name:
        audit.error(
            "SOURCE_HEADER_NAME",
            f"以下页面页眉未包含软件名称「{name}」：{format_pages(missing_name)}",
        )
    if missing_version:
        audit.error(
            "SOURCE_HEADER_VERSION",
            f"以下页面页眉未包含版本号「{version}」：{format_pages(missing_version)}",
        )

    text = "\n".join(line for page in pages for line in page.lines)
    placeholders = PLACEHOLDER_ERROR_RE.findall(text)
    if placeholders:
        audit.error(
            "SOURCE_PLACEHOLDER",
            f"源程序含占位内容（{', '.join(sorted(set(placeholders)))}），不能提交",
        )
    todo_pages = [
        str(page.number) for page in pages if TODO_RE.search("\n".join(page.lines))
    ]
    if todo_pages:
        audit.warning(
            "SOURCE_TODO",
            f"源程序第 {', '.join(todo_pages[:10])} 页含 TODO/FIXME；如为真实注释可保留，否则请清理",
        )
    if PRIVATE_KEY_RE.search(text):
        audit.error("SOURCE_SECRET", "源程序中检测到私钥块，必须移除后再提交")
    secret_pages = [
        str(page.number) for page in pages if SECRET_ASSIGN_RE.search("\n".join(page.lines))
    ]
    if secret_pages:
        audit.warning(
            "SOURCE_SECRET_ASSIGN",
            f"源程序第 {', '.join(secret_pages[:10])} 页出现疑似密钥/口令赋值，请人工确认",
        )

    if sidecar:
        if sidecar.get("pages") != len(pages):
            audit.warning(
                "SOURCE_SIDECAR",
                f"附带清单记录 {sidecar.get('pages')} 页，实际 {len(pages)} 页",
            )
        if sidecar.get("selected") == "first_last" and len(pages) != 60:
            audit.error("SOURCE_SELECTION", "清单标记为前30页+后30页，但实际不是 60 页")
        if sidecar.get("name") and name and sidecar.get("name") != name:
            audit.warning("SOURCE_SIDECAR", "附带清单中的软件名称与参数不一致")
        if sidecar.get("version") and version and sidecar.get("version") != version:
            audit.warning("SOURCE_SIDECAR", "附带清单中的版本号与参数不一致")
    else:
        audit.warning(
            "SOURCE_SIDECAR_MISSING",
            "未找到 source_doc.manifest.json，无法核对源码总量和前后页选择",
        )


def check_evidence(
    path: Path,
    info: Optional[dict],
    manual_path: Optional[Path],
    sidecar: Optional[dict],
    audit: Audit,
) -> None:
    data = load_json_object(path)
    if data.get("schema") != SCHEMA_VERSION:
        audit.error("EVIDENCE_SCHEMA", f"{path} 的 schema 不是 {SCHEMA_VERSION}")

    features = data.get("features")
    if not isinstance(features, list) or not features:
        audit.error("EVIDENCE_EMPTY", f"{path} 没有 features 数组或为空")
        return
    if manual_path is None:
        audit.error("EVIDENCE_MANUAL", "证据映射需要 --manual 用户手册")
    if info is None:
        audit.error("EVIDENCE_INFO", "证据映射需要 --info 申请表信息")

    source_files: Optional[set] = None
    visible_files: set = set()
    if sidecar is None:
        audit.error("EVIDENCE_MANIFEST", "证据映射需要 render 生成的 .manifest.json")
    else:
        raw_source_files = sidecar.get("source_files")
        if not isinstance(raw_source_files, list):
            audit.error("EVIDENCE_SOURCE_FILES", "源程序清单缺少 source_files，请重新 render")
        else:
            source_files = {str(item) for item in raw_source_files}
        raw_pages = sidecar.get("page_files")
        if isinstance(raw_pages, list):
            for page in raw_pages:
                if isinstance(page, list):
                    visible_files.update(str(item) for item in page)

    manual_raw = ""
    headings: List[str] = []
    if manual_path is not None:
        manual_raw, manual_text_value = manual_text(manual_path)
        headings = manual_headings(manual_path, manual_raw, manual_text_value)
        if not headings:
            audit.warning(
                "EVIDENCE_MANUAL_HEADINGS",
                "用户手册未识别到标题，无法核对 manual_section；建议使用 Markdown/HTML 标题",
            )

    haystack = ""
    if info:
        haystack = "\n".join(
            str(info.get(key) or "") for key in ("main_functions", "technical_features")
        )
        info_name = str(info.get("software_name") or "").strip()
        info_version = str(info.get("version") or "").strip()
        ev_name = str(data.get("software_name") or "").strip()
        ev_version = str(data.get("version") or "").strip()
        if ev_name and info_name and ev_name != info_name:
            audit.error("EVIDENCE_NAME", f"证据映射名称「{ev_name}」与申请表「{info_name}」不一致")
        if ev_version and info_version and ev_version != info_version:
            audit.error(
                "EVIDENCE_VERSION",
                f"证据映射版本号「{ev_version}」与申请表「{info_version}」不一致",
            )

    seen_names: set = set()
    code_count = 0
    screenshot_count = 0
    heading_text = re.sub(r"\s+", "", " ".join(headings))
    haystack_norm = re.sub(r"\s+", "", haystack)
    for index, feature in enumerate(features, start=1):
        label = f"features[{index}]"
        if not isinstance(feature, dict):
            audit.error("EVIDENCE_FEATURE", f"{label} 不是对象")
            continue
        name = str(feature.get("name") or "").strip()
        if not name:
            audit.error("EVIDENCE_FEATURE_NAME", f"{label} 缺少 name")
            name = label
        elif name in seen_names:
            audit.error("EVIDENCE_FEATURE_DUPLICATE", f"功能名称重复：{name}")
        else:
            seen_names.add(name)

        code_paths = feature.get("code_paths")
        if not isinstance(code_paths, list) or not code_paths:
            audit.error("EVIDENCE_CODE_PATH", f"{name} 缺少 code_paths")
        else:
            for code_path in code_paths:
                code_path = str(code_path).strip()
                if not code_path:
                    audit.error("EVIDENCE_CODE_PATH", f"{name} 的 code_paths 含空值")
                    continue
                code_count += 1
                if source_files is not None and code_path not in source_files:
                    audit.error(
                        "EVIDENCE_CODE_PATH",
                        f"{name} 的代码路径不在源程序清单：{code_path}",
                    )
                if visible_files and code_path not in visible_files:
                    audit.warning(
                        "EVIDENCE_CODE_NOT_VISIBLE",
                        f"{name} 的代码 {code_path} 未出现在提交的 60 页源程序中",
                    )

        manual_section = str(feature.get("manual_section") or "").strip()
        if not manual_section:
            audit.error("EVIDENCE_MANUAL_SECTION", f"{name} 缺少 manual_section")
        elif headings and re.sub(r"\s+", "", manual_section) not in heading_text:
            audit.error(
                "EVIDENCE_MANUAL_SECTION",
                f"{name} 的手册章节「{manual_section}」未在用户手册标题中找到",
            )

        screenshots = feature.get("screenshots")
        if not isinstance(screenshots, list) or not screenshots:
            audit.error("EVIDENCE_SCREENSHOT", f"{name} 至少需要一张真实截图")
        else:
            for screenshot in screenshots:
                screenshot = str(screenshot).strip()
                if not screenshot:
                    audit.error("EVIDENCE_SCREENSHOT", f"{name} 的 screenshots 含空值")
                    continue
                screenshot_count += 1
                shot_path = (path.parent / screenshot).resolve()
                if not shot_path.is_file():
                    audit.error(
                        "EVIDENCE_SCREENSHOT_MISSING",
                        f"{name} 的截图不存在：{screenshot}（相对证据映射文件）",
                    )
                elif shot_path.stat().st_size == 0:
                    audit.error(
                        "EVIDENCE_SCREENSHOT_EMPTY",
                        f"{name} 的截图为空文件：{screenshot}",
                    )
                elif not is_image_file(shot_path):
                    audit.error(
                        "EVIDENCE_SCREENSHOT_FORMAT",
                        f"{name} 的截图不是常见图片格式或已损坏：{screenshot}",
                    )
                if manual_raw and Path(screenshot).name.lower() not in manual_raw.lower():
                    audit.warning(
                        "EVIDENCE_SCREENSHOT_UNREFERENCED",
                        f"{name} 的截图 {Path(screenshot).name} 未在用户手册中引用",
                    )

        application_text = str(feature.get("application_text") or "").strip()
        if not application_text:
            audit.error("EVIDENCE_APP_TEXT", f"{name} 缺少 application_text")
        else:
            if len(application_text) < 10:
                audit.warning(
                    "EVIDENCE_APP_TEXT_SHORT",
                    f"{name} 的 application_text 过短，建议填完整功能句",
                )
            if haystack and re.sub(r"\s+", "", application_text) not in haystack_norm:
                audit.error(
                    "EVIDENCE_APP_TEXT",
                    f"{name} 的 application_text 未出现在 main_functions / technical_features 中",
                )

    audit.stats["evidence_features"] = len(features)
    audit.stats["evidence_code_paths"] = code_count
    audit.stats["evidence_screenshots"] = screenshot_count
    if info and len(features) == 1 and len(str(info.get("main_functions") or "")) > 500:
        audit.warning(
            "EVIDENCE_COVERAGE",
            "功能描述超过 500 字，但证据映射只覆盖 1 个功能；建议按功能拆分映射",
        )


def check_ai_usage(path: Path, info: Optional[dict], audit: Audit) -> None:
    data = load_json_object(path)
    if data.get("schema") != SCHEMA_VERSION:
        audit.error("AI_USAGE_SCHEMA", f"{path} 的 schema 不是 {SCHEMA_VERSION}")

    used_code = str(data.get("used_ai_for_code") or "").strip().lower()
    used_docs = str(data.get("used_ai_for_docs") or "").strip().lower()
    allowed = {"no", "partial", "yes"}
    for field, value in (("used_ai_for_code", used_code), ("used_ai_for_docs", used_docs)):
        if value not in allowed:
            audit.error("AI_USAGE_VALUE", f"{field} 需为 no / partial / yes")

    declaration = str(data.get("declaration") or "").strip()
    code_declaration = str(data.get("code_declaration") or "").strip()
    docs_declaration = str(data.get("docs_declaration") or "").strip()
    for field, value in (
        ("declaration", declaration),
        ("code_declaration", code_declaration),
        ("docs_declaration", docs_declaration),
    ):
        if not value:
            audit.error("AI_USAGE_DECLARATION", f"ai-usage.json 缺少 {field}")
    if declaration and len(declaration) < 20:
        audit.warning("AI_USAGE_DECLARATION", "declaration 少于 20 字，可能不足以说明使用情况")

    if code_declaration:
        if used_code == "no":
            if not any(word in code_declaration for word in ("未使用", "人工", "自行", "手写")):
                audit.warning(
                    "AI_USAGE_DECLARATION_REVIEW",
                    "used_ai_for_code=no，但 code_declaration 未明确说明未使用/人工编写",
                )
        else:
            if AI_CODE_NO_CLAIM_RE.search(code_declaration):
                if used_code == "yes":
                    audit.error(
                        "AI_USAGE_DECLARATION_CONFLICT",
                        "code_declaration 称未使用 AI 编写代码，但 used_ai_for_code=yes；请改成真实表述",
                    )
                else:
                    audit.warning(
                        "AI_USAGE_DECLARATION_REVIEW",
                        "code_declaration 出现否定表述，但 used_ai_for_code=partial；请确认是否特指“生成/改写”",
                    )
            if not re.search(r"AI", code_declaration, re.IGNORECASE):
                audit.warning(
                    "AI_USAGE_DECLARATION_REVIEW",
                    "code_declaration 未提到 AI，请说明使用情况",
                )
    if docs_declaration:
        if used_docs == "no":
            if not any(word in docs_declaration for word in ("未使用", "人工", "自行", "手写")):
                audit.warning(
                    "AI_USAGE_DECLARATION_REVIEW",
                    "used_ai_for_docs=no，但 docs_declaration 未明确说明未使用/人工编写",
                )
        else:
            if AI_DOC_NO_CLAIM_RE.search(docs_declaration):
                if used_docs == "yes":
                    audit.error(
                        "AI_USAGE_DECLARATION_CONFLICT",
                        "docs_declaration 称未使用 AI 编写文档，但 used_ai_for_docs=yes；请改成真实表述",
                    )
                else:
                    audit.warning(
                        "AI_USAGE_DECLARATION_REVIEW",
                        "docs_declaration 出现否定表述，但 used_ai_for_docs=partial；请确认是否特指“生成/改写”",
                    )
            if not re.search(r"AI", docs_declaration, re.IGNORECASE):
                audit.warning(
                    "AI_USAGE_DECLARATION_REVIEW",
                    "docs_declaration 未提到 AI，请说明使用情况",
                )

    tools = data.get("tools")
    tool_list = []
    if isinstance(tools, list):
        tool_list = [str(item).strip() for item in tools if str(item).strip()]
    human_review = str(data.get("human_review") or "").strip()
    any_ai = used_code in {"partial", "yes"} or used_docs in {"partial", "yes"}
    if any_ai:
        if not isinstance(tools, list):
            audit.error("AI_USAGE_TOOLS", "使用过 AI 时 tools 必须是数组")
        elif not tool_list:
            audit.error("AI_USAGE_TOOLS", "使用过 AI 时 tools 不能为空")
        if not human_review:
            audit.error("AI_USAGE_HUMAN_REVIEW", "使用过 AI 时必须说明人工审核/修改情况")
        if declaration and not re.search(r"AI", declaration, re.IGNORECASE):
            audit.warning("AI_USAGE_DECLARATION_REVIEW", "declaration 未提到 AI，请明确说明使用情况")
    else:
        if declaration and "未使用" not in declaration:
            audit.warning(
                "AI_USAGE_DECLARATION_REVIEW",
                "used_ai_* 均为 no，但 declaration 未明确写「未使用」；请确认表述",
            )

    date_text = str(data.get("date") or "").strip()
    if date_text:
        parsed = parse_iso_date(date_text)
        if parsed is None:
            audit.error("AI_USAGE_DATE", "date 需为 YYYY-MM-DD")
        elif parsed > date.today():
            audit.error("AI_USAGE_DATE", "AI 使用声明日期不能晚于今天")

    info_ai = str((info or {}).get("ai_usage") or "").strip()
    if info_ai and declaration and info_ai not in declaration and declaration not in info_ai:
        audit.warning(
            "AI_USAGE_INFO_CONFLICT",
            "application-info.json 的 ai_usage 与 ai-usage.json 的 declaration 表述不完全一致，请人工核对",
        )

    audit.stats["ai_used_code"] = used_code or "unknown"
    audit.stats["ai_used_docs"] = used_docs or "unknown"


def issue_location(issue: Issue) -> str:
    if issue.file and issue.line:
        return f"（{issue.file}:{issue.line}）"
    if issue.file:
        return f"（{issue.file}）"
    return ""


def write_markdown_report(audit: Audit, path: Path) -> None:
    lines = [
        "# 软著材料自检报告",
        "",
        f"- 结果：{'通过' if audit.ok else '未通过'}",
        f"- 严格模式：{'是' if audit.strict else '否'}",
        "",
    ]
    if audit.stats:
        lines.extend(["## 统计", ""])
        for key, value in audit.stats.items():
            lines.append(f"- `{key}`：{value}")
        lines.append("")
    if audit.errors:
        lines.append(f"## 错误（{len(audit.errors)}）")
        lines.append("")
        for issue in audit.errors:
            lines.append(f"- `[{issue.code}]` {issue.message}{issue_location(issue)}")
        lines.append("")
    else:
        lines.extend(["## 错误（0）", "", "未发现错误。", ""])
    if audit.warnings:
        lines.append(f"## 警告（{len(audit.warnings)}）")
        lines.append("")
        for issue in audit.warnings:
            lines.append(f"- `[{issue.code}]` {issue.message}{issue_location(issue)}")
        lines.append("")
    else:
        lines.extend(["## 警告（0）", "", "未发现警告。", ""])
    lines.append("> 本报告只覆盖格式、字段和一致性检查，不代表中国版权保护中心的审查结论。")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    except OSError as exc:
        raise InputError(f"无法写入自检报告 {path}：{exc}")


def cmd_check(args: argparse.Namespace) -> int:
    audit = Audit(strict=args.strict)
    pages = parse_source_html(args.source_html)
    info = load_info(args.info) if args.info else None
    sidecar_path = args.sidecar or args.source_html.with_suffix(".manifest.json")
    sidecar = None
    if sidecar_path.exists():
        try:
            sidecar = json.loads(sidecar_path.read_text(encoding="utf-8-sig"))
        except (OSError, json.JSONDecodeError) as exc:
            audit.warning("SOURCE_SIDECAR_UNREADABLE", f"无法读取源程序清单：{exc}")
        else:
            if not isinstance(sidecar, dict) or sidecar.get("schema") != SCHEMA_VERSION:
                audit.warning("SOURCE_SIDECAR_INVALID", "源程序清单格式不匹配，已忽略")
                sidecar = None

    name = args.name or str((info or {}).get("software_name") or "").strip()
    version = args.version or str((info or {}).get("version") or "").strip()
    if not name:
        audit.error("NAME_MISSING", "需要 --name 或在申请表信息中提供 software_name")
    if not version:
        audit.error("VERSION_MISSING", "需要 --version 或在申请表信息中提供 version")

    check_source_pages(pages, name, version, sidecar, audit)
    if info:
        check_info(info, pages, sidecar, audit)
    else:
        audit.warning("INFO_MISSING", "未提供 --info，跳过申请表字段一致性校验")
    if args.manual:
        check_manual(args.manual, info, pages, audit)
    if args.evidence:
        check_evidence(args.evidence, info, args.manual, sidecar, audit)
    if args.ai_usage:
        check_ai_usage(args.ai_usage, info, audit)
    elif args.evidence:
        audit.warning(
            "AI_USAGE_MISSING",
            "提供了证据映射但未提供 ai-usage.json；建议同时记录 AI 使用声明",
        )
    if args.report:
        write_markdown_report(audit, args.report)

    if args.as_json:
        payload = {
            "ok": audit.ok,
            "strict": audit.strict,
            "stats": audit.stats,
            "errors": [issue.as_dict() for issue in audit.errors],
            "warnings": [issue.as_dict() for issue in audit.warnings],
        }
        print(json.dumps(payload, ensure_ascii=False, indent=2))
    else:
        print("软著材料自检")
        print(
            f"源程序：{audit.stats.get('source_pages', 0)} 页，"
            f"{audit.stats.get('source_visible_lines', 0)} 个显示行"
        )
        if info:
            print("申请表信息：已读取")
        if args.manual:
            print(
                f"用户手册：约 {audit.stats.get('manual_estimated_pages', 0)} 页，"
                f"{audit.stats.get('manual_images', 0)} 张图"
            )
        if args.evidence:
            print(
                f"证据映射：{audit.stats.get('evidence_features', 0)} 个功能，"
                f"{audit.stats.get('evidence_code_paths', 0)} 个代码路径，"
                f"{audit.stats.get('evidence_screenshots', 0)} 张截图"
            )
        if args.ai_usage:
            print(
                f"AI 使用声明：code={audit.stats.get('ai_used_code', 'unknown')}，"
                f"docs={audit.stats.get('ai_used_docs', 'unknown')}"
            )
        if audit.errors:
            print(f"\n错误（{len(audit.errors)}）：")
            for issue in audit.errors:
                print(f"  [{issue.code}] {issue.message}")
        if audit.warnings:
            print(f"\n警告（{len(audit.warnings)}）：")
            for issue in audit.warnings:
                print(f"  [{issue.code}] {issue.message}")
        print("\n结果：" + ("通过" if audit.ok else "未通过"))
    return 0 if audit.ok else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="中国软件著作权登记材料辅助工具：扫描真实源码、生成源程序文档、自检材料。",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    scan = sub.add_parser("scan", help="扫描项目源码并生成清单")
    scan.add_argument("--project", type=Path, required=True, help="真实项目目录")
    scan.add_argument("--out", type=Path, required=True, help="输出目录（source_manifest.json / source_stats.md）")
    scan.add_argument("--include-tests", action="store_true", help="纳入测试目录与测试文件")
    scan.add_argument(
        "--include-ext", nargs="+", default=None,
        help="额外纳入的扩展名（在默认源码类型之外），如 .json .yaml",
    )
    scan.add_argument(
        "--max-file-bytes", type=int, default=DEFAULT_MAX_FILE_BYTES,
        help=f"单文件大小上限（默认 {DEFAULT_MAX_FILE_BYTES} 字节）",
    )

    render = sub.add_parser("render", help="生成 60 页源程序 HTML")
    render.add_argument("--manifest", type=Path, required=True, help="scan 生成的 source_manifest.json")
    render.add_argument("--project", type=Path, default=None, help="覆盖清单中的项目根目录")
    render.add_argument("--name", required=True, help="软件全称（与申请表一致）")
    render.add_argument("--version", required=True, help="版本号（与申请表一致，如 V1.0）")
    render.add_argument("--out", type=Path, required=True, help="输出 HTML 路径")
    render.add_argument("--max-pages", type=int, default=DEFAULT_MAX_PAGES, help="最大页数，默认 60")
    render.add_argument("--max-cols", type=int, default=DEFAULT_MAX_COLS, help="每行最大半角列数，默认 90")
    render.add_argument("--keep-blank-lines", action="store_true", help="保留源码空行")

    check = sub.add_parser("check", help="自检源程序、申请表与用户手册")
    check.add_argument("--source-html", type=Path, required=True, help="render 生成的源程序 HTML")
    check.add_argument("--info", type=Path, default=None, help="application-info.json")
    check.add_argument("--manual", type=Path, default=None, help="用户手册 Markdown/HTML")
    check.add_argument("--evidence", type=Path, default=None, help="证据映射 evidence-map.json")
    check.add_argument("--ai-usage", type=Path, default=None, help="AI 使用声明 ai-usage.json")
    check.add_argument("--sidecar", type=Path, default=None, help="源程序清单 JSON（默认自动查找）")
    check.add_argument("--name", default=None, help="软件全称（不填则从 info 读取）")
    check.add_argument("--version", default=None, help="版本号（不填则从 info 读取）")
    check.add_argument("--strict", action="store_true", help="把警告也视为失败")
    check.add_argument("--json", action="store_true", dest="as_json", help="输出 JSON 报告")
    check.add_argument("--report", type=Path, default=None, help="输出 Markdown 自检报告")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        if args.command == "scan":
            return cmd_scan(args)
        if args.command == "render":
            return cmd_render(args)
        if args.command == "check":
            return cmd_check(args)
        raise InputError(f"未知子命令：{args.command}")
    except InputError as exc:
        print(f"错误：{exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
